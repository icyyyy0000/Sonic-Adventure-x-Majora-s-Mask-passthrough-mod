"""Build a .nrm using portable LLVM; no system changes required."""
import argparse
import subprocess
import zipfile
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT.parents[1] / 'work'
def run(cmd):
    subprocess.run([str(x) for x in cmd], cwd=ROOT, check=True)
def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--llvm', type=Path, default=WORK / 'tools/llvm18/bin')
    parser.add_argument('--mod-tool', type=Path, default=WORK / 'tools/RecompModTool.exe')
    parser.add_argument('--bridge', action='store_true')
    args = parser.parse_args()
    if not args.bridge and not (ROOT / 'src/generated/sonic_model.c').exists():
        raise SystemExit('Run extract_models.py with your SADX directory first.')
    (ROOT / 'build').mkdir(exist_ok=True)
    flags = ['-target', 'mips', '-mips2', '-mabi=32', '-O2', '-G0', '-mno-abicalls',
             '-mno-odd-spreg', '-mno-check-zero-division', '-fomit-frame-pointer',
             '-ffast-math', '-fno-unsafe-math-optimizations', '-fno-builtin-memset',
             '-Wall', '-Wextra', '-Wno-incompatible-library-redeclaration',
             '-Wno-unused-parameter', '-Wno-unknown-pragmas', '-Wno-unused-variable',
             '-Wno-missing-braces', '-Wno-unsupported-floating-point-opt', '-Werror=section',
             '-D_LANGUAGE_C', '-nostdinc', '-ffunction-sections', '-DMIPS', '-DF3DEX_GBI_2',
             '-DF3DEX_GBI_PL', '-DGBI_DOWHILE', '-Iinclude', '-Iinclude/dummy_headers', '-Isrc', '-Iprotocol',
             '-Imm-decomp/include', '-Imm-decomp/src', '-Imm-decomp/extracted/n64-us',
             '-idirafter', 'include/libc', '-idirafter', 'mm-decomp/include/libc']
    objects = []
    sources = ROOT / ('bridge/src' if args.bridge else 'src')
    for src in sorted(sources.rglob('*.c')):
        obj = ROOT / 'build' / src.relative_to(ROOT).with_suffix('.o')
        obj.parent.mkdir(parents=True, exist_ok=True)
        print(f'Compiling {src.relative_to(ROOT)}', flush=True)
        run([args.llvm / 'clang.exe', *flags, '-c', src, '-o', obj])
        objects.append(obj)
    elf = 'build/observer.elf' if args.bridge else 'build/mod.elf'
    run([args.llvm / 'ld.lld.exe', *objects, '-nostdlib', '-T', 'mod.ld', '-Map', elf + '.map',
         '--unresolved-symbols=ignore-all', '--emit-relocs', '-e', '0', '--no-nmagic', '-gc-sections',
         '-o', elf])
    # RecompModTool writes validated metadata before invoking system ZIP tools.
    # Some Windows hosts cannot load Compress-Archive; use Python's ZIP writer
    # only if all validated outputs were regenerated by this tool invocation.
    metadata = [ROOT / 'build' / n for n in ('mod.json', 'mod_syms.bin', 'mod_binary.bin')]
    for path in metadata:
        if path.exists(): path.unlink()
    result = subprocess.run([str(args.mod_tool), 'bridge/mod.toml' if args.bridge else 'mod.toml', 'build'], cwd=ROOT, capture_output=True, text=True)
    if result.returncode and (not all(p.exists() for p in metadata) or 'Compress-Archive failed' not in result.stdout + result.stderr):
        print(result.stdout + result.stderr)
        raise SystemExit(result.returncode)
    manifest = json.loads(metadata[0].read_text())
    destination = ROOT / 'build' / f'{manifest["id"]}-{manifest["version"]}.nrm'
    with zipfile.ZipFile(destination, 'w', zipfile.ZIP_DEFLATED) as archive:
        for path in metadata: archive.write(path, path.name)
    print(f'Built {destination.name} ({destination.stat().st_size:,} bytes)')
if __name__ == '__main__':
    main()
